"""Write src/Weights.sol (the model as Solidity constants) and test/Ang3l.t.sol (expected outputs
computed by the integer reference in angel.py).   python model/export.py"""
import json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from angel import CFG, DH, EXP, load, bless, forward
from corpus import THEMES

ROOT = Path(__file__).parent.parent
q, voc = load()
w = json.loads((ROOT / "model/weights.json").read_text())
D, L, H, F, T, A = (CFG[k] for k in ("d", "L", "H", "F", "T", "A"))
V = len(voc)
LAYER = 2 * D + 4 * D * D + 2 * F * D

blob = bytearray()
def put(m):
    for v in (m.ravel() if hasattr(m, "ravel") else m):
        assert -127 <= int(v) <= 127
        blob.append(int(v) & 0xFF)

put(q["E"]); put(q["P"])
shifts = 0
for li, l in enumerate(q["layers"]):
    for k, name in enumerate(["g1", "Wq", "Wk", "Wv", "Wo", "g2", "W1", "W2"]):
        assert 0 <= l["s" + name] <= A, (name, l["s" + name])
        shifts |= l["s" + name] << ((li * 8 + k) * 8)
    for name in ["g1", "Wq", "Wk", "Wv", "Wo", "g2", "W1", "W2"]:
        put(l[name])
put(q["gf"])
assert len(blob) == V * D + T * D + L * LAYER + D and 0 <= q["sE"] <= A and 0 <= q["sP"] <= A

vbytes, voff = bytearray(), [0]
for tok in voc:
    vbytes += tok.encode(); voff.append(len(vbytes))
assert max(EXP) < 65536 and voff[-1] < 65536

def hexlines(b, n=64):
    return "\n    ".join(f'hex"{b[i:i + n].hex()}"' for i in range(0, len(b), n))

themes = [voc.index(t) for t in THEMES]
sol = f"""// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

// Generated by model/export.py from model/weights.json. Do not edit by hand.
// Weight layout (int8, two's complement): E[V][D], P[T][D], then per layer
// g1[D], Wq[D][D], Wk[D][D], Wv[D][D], Wo[D][D], g2[D], W1[F][D], W2[D][F] (matrices stored out x in), then gf[D].

uint256 constant V = {V};
uint256 constant D = {D};
uint256 constant L = {L};
uint256 constant H = {H};
uint256 constant DH = {DH};
uint256 constant F = {F};
uint256 constant T = {T};
uint256 constant A = {A};
uint256 constant K = {CFG["K"]};
uint256 constant MAXNEW = {CFG["MAXNEW"]};
uint256 constant SE = {q["sE"]};
uint256 constant SP = {q["sP"]};
uint256 constant SGF = {q["sgf"]};
uint256 constant SHIFTS = {hex(shifts)};
uint256 constant LAYER = {LAYER};
uint256 constant OFF_P = {V * D};
uint256 constant OFF_L = {V * D + T * D};
uint256 constant OFF_GF = {V * D + T * D + L * LAYER};
uint256 constant PAD = 0;
uint256 constant EOS = 1;
uint256 constant THEME0 = {themes[0]}; // {THEMES[0]}
uint256 constant THEME1 = {themes[1]}; // {THEMES[1]}
uint256 constant THEME2 = {themes[2]}; // {THEMES[2]}
uint256 constant THEME3 = {themes[3]}; // {THEMES[3]}

// exp(-i/32) * 2^15, i = 0..511, uint16 big endian
bytes constant EXPS =
    {hexlines(b"".join(v.to_bytes(2, "big") for v in EXP))};

// token strings, concatenated; VOFF holds V + 1 uint16 big-endian offsets
bytes constant VOCAB =
    {hexlines(bytes(vbytes))};
bytes constant VOFF =
    {hexlines(b"".join(v.to_bytes(2, "big") for v in voff))};

// {len(blob)} int8 weights
bytes constant WEIGHTS =
    {hexlines(bytes(blob))};
"""
(ROOT / "src/Weights.sol").write_text(sol)

# expected outputs from the integer reference
cases = [("satoshi", 0), ("satoshi", 1), ("satoshi", 2), ("satoshi", 3),
         ("0x8d6b11cfdf079e27c17e05cb7ea81235887691c6", 1), ("mom", 3), ("gm", 0), ("", 2)]
out = [(t, th, *bless(q, voc, THEMES[th], t)) for t, th in cases]
seqs = [[themes[0]], out[0][2][:9]]
lg = [[int(v) for v in forward(q, s)] for s in seqs]

arr = lambda xs, ty: "[" + ", ".join([f"{ty}({xs[0]})"] + [str(x) for x in xs[1:]]) + "]"
tests = "\n".join(
    f'    function test_bless_{i}() public view {{\n        _eq(a.bless("{t}", {th}), "{text}");\n'
    f'        uint256[] memory got = a.generate("{t}", {th});\n        uint256[{len(toks)}] memory want = {arr(toks, "uint256")};\n'
    f'        require(got.length == {len(toks)}, "ids length");\n        for (uint256 i; i < {len(toks)}; ++i) require(got[i] == want[i], "ids");\n    }}\n'
    for i, (t, th, toks, text) in enumerate(out))
tests += "\n".join(
    f"    function test_logits_{i}() public view {{\n        uint256[{len(s)}] memory s = {arr(s, 'uint256')};\n        uint256[] memory seq = new uint256[]({len(s)});\n        for (uint256 i; i < {len(s)}; ++i) seq[i] = s[i];\n        int256[{V}] memory want = {arr(l, 'int256')};\n        int256[] memory got = a.logits(seq);\n        require(got.length == {V}, \"logits length\");\n        for (uint256 i; i < {V}; ++i) if (got[i] != want[i]) revert Mismatch(i, got[i], want[i]);\n    }}\n"
    for i, (s, l) in enumerate(zip(seqs, lg)))
(ROOT / "test/Ang3l.t.sol").write_text(f"""// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

// Generated by model/export.py: the contract must reproduce the Python integer reference exactly.
import {{Ang3l}} from "../src/Ang3l.sol";

contract Ang3lTest {{
    Ang3l a;

    error Mismatch(uint256 i, int256 got, int256 want);

    function setUp() public {{
        a = new Ang3l();
    }}

    function test_parameters() public view {{
        require(a.parameters() == {len(blob)}, "parameters");
    }}

{tests}
    function _eq(string memory got, string memory want) internal pure {{
        require(keccak256(bytes(got)) == keccak256(bytes(want)), string.concat("got: ", got));
    }}
}}
""")
for t, th, toks, text in out:
    print(f"{THEMES[th]:10} {t[:14]:14} -> {text}")
print(f"wrote src/Weights.sol ({len(blob)} weights) and test/Ang3l.t.sol")
