"""Synthetic training corpus: short blessings in four themes, generated from a small grammar.

Every line is "<theme> words ... ." and the model learns to continue a theme token into a blessing.
No outside text is used, so the corpus can be regenerated byte for byte from this file.
"""
import random

THEMES = ["<builder>", "<holder>", "<night>", "<friend>"]

LIGHT = ["the light", "the morning", "the quiet sun", "a gentle wind", "the first star", "an old song",
         "the long road", "the open sky", "a calm sea", "the patient moon", "a warm fire", "the river"]
GOOD = ["kind", "steady", "gentle", "bright", "calm", "patient", "brave", "honest", "light", "clear", "strong", "warm"]
GIFT = ["peace", "courage", "patience", "rest", "clarity", "joy", "strength", "grace", "luck", "hope", "focus", "wonder"]
WHEN = ["tonight", "today", "tomorrow", "this week", "at dawn", "before the next block", "until morning",
        "all season", "every day", "when it counts", "in the quiet hours", "for a long while"]
VERB = ["walk beside you", "keep watch over you", "find you", "carry you", "stay with you", "guide your hands",
        "guard your keys", "light your path", "steady your heart", "wait for you", "hold your name", "follow your steps"]

BY_THEME = {
    "<builder>": dict(
        thing=["your code", "your build", "your tests", "your contract", "your design", "your launch", "your work", "your idea"],
        wish=["compile on the first try", "pass every test", "ship on time", "find its users", "run without a bug",
              "deploy in one block", "stand for years", "make someone smile"],
        nouns=["builder", "maker", "dreamer", "worker", "craftsman"],
        lines=["may {thing} {wish} .", "may {thing} {wish} , and may {light} {verb} {when} .",
               "build with {gift} , {noun} , for {light} is watching .", "your hands are {good} and {thing} is {good} .",
               "rest when you need to , {noun} ; {thing} will still be here {when} .",
               "i bless {thing} with {gift} and {gift} .", "may your gas be low and your {gift} be high .",
               "{when} , {thing} will {wish} .", "be {good} , be {good} , and let {thing} {wish} ."]),
    "<holder>": dict(
        thing=["your keys", "your wallet", "your conviction", "your patience", "your bag", "your heart", "your plan", "your hands"],
        wish=["stay safe", "stay calm", "hold steady", "grow wise", "stay light", "remain yours", "find its reward", "rest easy"],
        nouns=["holder", "believer", "friend", "keeper", "watcher"],
        lines=["may {thing} {wish} {when} .", "hold with {gift} , {noun} , and let {light} {verb} .",
               "your keys are safe , your heart is {good} , and {light} will {verb} .",
               "i bless {thing} with {gift} , {when} .", "do not fear the red candle ; {light} will {verb} .",
               "may your gas be low and your {gift} be long .", "{when} , {thing} will {wish} .",
               "be {good} , {noun} ; {thing} will {wish} .", "even in the dip , {light} will {verb} ."]),
    "<night>": dict(
        thing=["your sleep", "your dreams", "your rest", "your mind", "your room", "your breath", "your night", "your house"],
        wish=["be deep", "be quiet", "be soft", "be safe", "be still", "be warm", "be long", "be kind"],
        nouns=["sleeper", "dreamer", "traveler", "wanderer", "friend"],
        lines=["may {thing} {wish} {when} .", "sleep now , {noun} , for {light} will {verb} .",
               "close your eyes ; {light} will {verb} {when} .", "i bless {thing} with {gift} and {gift} .",
               "do not fear the dark ; {light} will {verb} .", "{when} , {light} will {verb} .",
               "rest , {noun} ; the chain keeps turning without you .", "even in the dark , {light} will {verb} .",
               "be {good} with yourself {when} ."]),
    "<friend>": dict(
        thing=["your day", "your heart", "your road", "your family", "your laugh", "your work", "your home", "your mind"],
        wish=["be bright", "be full", "be easy", "be kind to you", "find its way", "be blessed", "be light", "be good"],
        nouns=["friend", "stranger", "traveler", "neighbor", "kind soul"],
        lines=["may {thing} {wish} {when} .", "hello , {noun} . i bless {thing} with {gift} .",
               "you are {good} , {noun} , and {light} will {verb} .", "may {light} {verb} {when} .",
               "i see you , {noun} ; {thing} will {wish} .", "{when} , {thing} will {wish} .",
               "be {good} , be {good} , and let {light} {verb} .", "go with {gift} , {noun} , and come back with {gift} ."]),
}


def line(theme, rng):
    t = BY_THEME[theme]
    s = rng.choice(t["lines"])
    while "{" in s:  # fill one slot at a time so a slot used twice gets two picks
        for key, pool in (("{thing}", t["thing"]), ("{wish}", t["wish"]), ("{noun}", t["nouns"]), ("{light}", LIGHT),
                          ("{good}", GOOD), ("{gift}", GIFT), ("{when}", WHEN), ("{verb}", VERB)):
            if key in s:
                s = s.replace(key, rng.choice(pool), 1)
    return f"{theme} {s}"


MAXWORDS = 18   # keeps a whole blessing inside one 50M-gas read call


def corpus(n=60000, seed=7):
    rng = random.Random(seed)
    out = []
    while len(out) < n:
        l = line(rng.choice(THEMES), rng)
        if len(l.split()) - 1 <= MAXWORDS:
            out.append(l)
    return out


if __name__ == "__main__":
    c = corpus()
    words = sorted({w for l in c for w in l.split()})
    assert all(len(l.split()) - 1 <= MAXWORDS for l in c)
    print(len(c), "lines,", len(words), "distinct tokens, longest", max(len(l.split()) for l in c))
    for l in c[:6]:
        print(" ", l)
