def line(theme, rng):
    t = BY_THEME[theme]
    s = rng.choice(COMMON) if rng.random() < 0.7 else rng.choice(t["extra"])
    pools = (("{thing}", t["thing"]), ("{wish}", t["wish"]), ("{noun}", t["noun"]), ("{hard}", t["hard"]),
             ("{light}", LIGHT), ("{verb}", VERB), ("{good}", GOOD), ("{gift}", GIFT), ("{when}", WHEN))
    while "{" in s:  # fill one slot at a time so a slot used twice gets two picks
        if "{name}" in s:
            s = s.replace("{name}", "<name>", 1)
        for key, pool in pools:
            if key in s:
                s = s.replace(key, rng.choice(pool), 1)
    return f"{theme} {s}"


def corpus(n=80000, seed=7):
    rng = random.Random(seed)
    out = []
    while len(out) < n:
        l = line(rng.choice(THEMES), rng)
        if len(l.split()) - 1 <= MAXWORDS:
            out.append(l)
    return out


